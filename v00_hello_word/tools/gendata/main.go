// Command gendata extracts the graphics of the original Digger sources
// (vgagrafx.c, alpha.c, title_gz.c) into web/js/data.js.
//
// Usage: go run ./tools/gendata ../digger > web/js/data.js
package main

import (
	"encoding/base64"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

var (
	arrayRe = regexp.MustCompile(`(?s)static const uint8_t (\w+)\[\w*\]\s*=\s*\{(.*?)\};`)
	numRe   = regexp.MustCompile(`0x[0-9a-fA-F]+|\d+`)
	nameRe  = regexp.MustCompile(`\b(vga\w+|0)\b`)
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: gendata <path to digger sources>")
	}
	dir := os.Args[1]

	vga := read(dir, "vgagrafx.c")
	alpha := read(dir, "alpha.c")
	title := read(dir, "title_gz.c")

	arrays := parseArrays(vga)
	for name, data := range parseArrays(alpha) {
		arrays[name] = data
	}

	sprites := tableNames(vga, "vgatable")
	font := tableNames(alpha, "ascii2vga")

	fmt.Println("// Generated by tools/gendata from the original Digger sources. DO NOT EDIT.")
	fmt.Println()
	fmt.Println("// Bitmaps, one byte per pixel at 640x400, indexed like vgatable[] in vgagrafx.c:")
	fmt.Println("// sprite n is at 2n, its mask at 2n+1.")
	fmt.Println("export const sprites = [")
	for _, name := range sprites {
		fmt.Printf("  %q,\n", encode(arrays, name))
	}
	fmt.Println("];")
	fmt.Println()
	fmt.Println("// Font bitmaps for characters 32..126, null where there is none.")
	fmt.Println("export const font = [")
	for _, name := range font {
		if name == "0" {
			fmt.Println("  null,")
			continue
		}
		fmt.Printf("  %q,\n", encode(arrays, name))
	}
	fmt.Println("];")
	fmt.Println()
	fmt.Println("// Title screen, 640x400, zlib compressed.")
	fmt.Printf("export const title = %q;\n", encodeBytes(parseTitle(title)))
}

func read(dir, name string) string {
	b, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		log.Fatal(err)
	}
	return string(b)
}

func parseArrays(src string) map[string][]byte {
	arrays := map[string][]byte{}
	for _, m := range arrayRe.FindAllStringSubmatch(src, -1) {
		arrays[m[1]] = parseBytes(m[2])
	}
	return arrays
}

func parseBytes(s string) []byte {
	var out []byte
	for _, n := range numRe.FindAllString(s, -1) {
		v, err := strconv.ParseUint(n, 0, 8)
		if err != nil {
			log.Fatalf("bad byte %q: %v", n, err)
		}
		out = append(out, byte(v))
	}
	return out
}

// tableNames returns the array names listed in a C pointer table.
func tableNames(src, table string) []string {
	start := strings.Index(src, table+"[")
	if start < 0 {
		log.Fatalf("table %s not found", table)
	}
	body := src[start:]
	body = body[strings.Index(body, "{")+1 : strings.Index(body, "};")]
	var names []string
	for _, line := range strings.Split(body, "\n") {
		if i := strings.Index(line, "/*"); i >= 0 {
			line = line[:i]
		}
		names = append(names, nameRe.FindAllString(line, -1)...)
	}
	return names
}

func parseTitle(src string) []byte {
	start := strings.Index(src, "title_gz[")
	body := src[start:]
	body = body[strings.Index(body, "{")+1 : strings.Index(body, "};")]
	return parseBytes(body)
}

func encode(arrays map[string][]byte, name string) string {
	data, ok := arrays[name]
	if !ok {
		log.Fatalf("array %s not found", name)
	}
	return encodeBytes(data)
}

func encodeBytes(b []byte) string {
	return base64.StdEncoding.EncodeToString(b)
}
